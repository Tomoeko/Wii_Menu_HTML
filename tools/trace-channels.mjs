#!/usr/bin/env node
import { formatJson } from './format-json.mjs';
/** Numeric browser/source pose audit. This tool does not produce screenshots. */
import { readFile, realpath, writeFile, mkdir } from 'node:fs/promises';
import { createWriteStream } from 'node:fs';
import { createGzip } from 'node:zlib';
import { once } from 'node:events';
import { finished } from 'node:stream/promises';
import { resolve, join, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { channelClips, poseChannel } from '../web/src/channel-animation.js';
import { walkPanes } from '../web/src/animation.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2),
  options = {
    assets: join(root, 'web/public/assets'),
    output: join(root, 'artifacts/channel-traces'),
    frames: 3600,
  };
for (let i = 0; i < args.length; i++) {
  const key = args[i].replace(/^--/, '');
  if (!['assets', 'output', 'frames'].includes(key) || !args[i + 1])
    throw new Error(
      'Usage: node tools/trace-channels.mjs [--assets DIR] [--output DIR] [--frames 1..36000]',
    );
  options[key] = key === 'frames' ? Number(args[++i]) : resolve(args[++i]);
}
if (!Number.isInteger(options.frames) || options.frames < 1 || options.frames > 36000)
  throw new Error('--frames must be an integer from 1 to 36000');
const json = async (path) => JSON.parse(await readFile(path, 'utf8'));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
await mkdir(options.output, { recursive: true });
const assets = await realpath(options.assets);
async function assetFile(resource) {
  if (typeof resource !== 'string' || !resource) {
    throw new Error('Invalid trace resource path.');
  }
  const candidate = resolve(assets, resource);
  if (!candidate.startsWith(assets + sep)) {
    throw new Error('Trace resource escapes the assets directory.');
  }
  const path = await realpath(candidate);
  if (!path.startsWith(assets + sep)) {
    throw new Error('Trace resource escapes the assets directory.');
  }
  return path;
}
const catalog = await json(await assetFile('channels.json'));
const manifest = await json(await assetFile('manifest.json'));
if (!Array.isArray(catalog.channels)) throw new Error('Invalid channel trace catalog.');
const fonts = {};
for (const [name, value] of Object.entries(manifest.fonts || {}))
  fonts[name] = await json(await assetFile(value.url));
const measureText = (text, pane, layout) => {
  const font = fonts[layout.fonts[pane.font]],
    scale = font ? pane.fontSize[0] / font.width : 0;
  if (!font)
    throw new Error(
      `Missing source font ${layout.fonts[pane.font]} required for scripted text measurement`,
    );
  return [...text].reduce(
    (sum, c, i) =>
      sum +
      (font.glyphs[font.characters[c.codePointAt(0)] ?? font.defaultGlyph]?.advance || 0) * scale +
      (i ? pane.charSpace || 0 : 0),
    0,
  );
};
const poseOptions = { language: catalog.language || 'ENG', measureText, networkConfigured: false };

function numericState(layout) {
  const records = {};
  walkPanes(layout.root, (pane) => {
    records[`pane/${pane.name}`] = {
      translation: pane.translation,
      rotation: pane.rotation,
      scale: pane.scale,
      size: pane.size,
      flags: pane.flags,
      alpha: pane.alpha,
      vertexColors: pane.vertexColors,
      fontSize: pane.fontSize,
      charSpace: pane.charSpace,
    };
  });
  for (const material of layout.materials)
    records[`material/${material.name}`] = {
      colors: material.colors,
      konstColors: material.konstColors,
      materialColor: material.materialColor,
      textureSRTs: material.textureSRTs,
      textureMaps: material.textureMaps,
    };
  return Object.fromEntries(
    Object.entries(records).map(([name, value]) => [name, JSON.stringify(value)]),
  );
}

const inventory = {
  schemaVersion: 1,
  kind: 'numeric-source-pose-trace',
  frames: options.frames,
  fps: 60,
  notice:
    'Generated by the browser scheduler and BRLAN evaluator using local source resources. This is not a native rendered capture or independent proof of pixel/timing fidelity.',
  assumptions: {
    language: poseOptions.language,
    networkConfigured: false,
    saveData: false,
    wiiConnect24Data: false,
  },
  channels: [],
};
for (const metadata of catalog.channels) {
  if (!metadata || typeof metadata.id !== 'string' || !/^[0-9a-f]{16}$/i.test(metadata.id)) {
    throw new Error('Invalid native channel ID in trace catalog.');
  }
  const channel = { ...metadata },
    layoutBytes = {},
    entry = {
      id: metadata.id,
      shortId: metadata.shortId,
      title: metadata.title,
      audio: metadata.audio,
      resources: {},
    };
  for (const kind of ['icon', 'banner']) {
    if (!metadata[`${kind}Layout`]) continue;
    const path = await assetFile(metadata[`${kind}Layout`]);
    layoutBytes[kind] = await readFile(path);
    channel[kind] = JSON.parse(layoutBytes[kind]);
  }
  for (const kind of ['icon', 'banner']) {
    const layout = channel[kind];
    if (!layout) continue;
    const filename = `${channel.id}-${kind}.jsonl.gz`,
      stream = createWriteStream(join(options.output, filename));
    const gzip = createGzip({ level: 6 });
    gzip.pipe(stream);
    const emit = async (value) => {
      if (!gzip.write(JSON.stringify(value) + '\n')) await once(gzip, 'drain');
    };
    const schedules = new Map();
    for (const frame of [0, 1, options.frames])
      for (const clip of channelClips(channel, kind, frame, poseOptions))
        schedules.set(clip.name, {
          name: clip.name,
          group: clip.group,
          recursive: clip.recursive,
          controller: clip.controller,
        });
    const resource = {
      source: layout.source,
      sourceSha256: layout.sourceSha256,
      layoutSha256: hash(layoutBytes[kind]),
      trace: filename,
      schedule: [...schedules.values()],
      animations: Object.entries(layout.animations).map(([name, a]) => ({
        name,
        frames: a.frames,
        loop: a.loop,
        controllerDefaultMax: Math.max(0, a.frames - (a.loop ? 0 : 1)),
        group: /_Rso(\d+)$/i.test(name) ? `Rso${/_Rso(\d+)$/i.exec(name)[1]}` : null,
        scheduled: [...schedules.keys()].some((s) => s.toLowerCase() === name.toLowerCase()),
        tracks: a.targets.flatMap((target) =>
          target.tracks.map((track) => ({
            targetName: target.name,
            targetType: target.type,
            kind: track.kind,
            id: track.id,
            target: track.target,
            curveType: track.curveType,
            keyCount: track.keys.length,
            firstFrame: track.keys[0]?.frame,
            lastFrame: track.keys.at(-1)?.frame,
          })),
        ),
      })),
    };
    await emit({
      type: 'header',
      schemaVersion: 1,
      kind: 'numeric-source-pose-trace',
      id: channel.id,
      resource: kind,
      frames: options.frames,
      fps: 60,
      assumptions: inventory.assumptions,
      layoutSha256: resource.layoutSha256,
      encoding:
        'frame0 contains all records; subsequent frames contain only changed pane/material records. Missing records retain their last state.',
    });
    let previous = {},
      changes = 0;
    for (let frame = 0; frame <= options.frames; frame++) {
      const pose = poseChannel(channel, kind, frame, poseOptions),
        state = numericState(pose),
        delta = {};
      for (const [name, value] of Object.entries(state))
        if (previous[name] !== value) {
          delta[name] = JSON.parse(value);
          changes++;
        }
      await emit({
        frame,
        clips: channelClips(channel, kind, frame, poseOptions).map((c) => ({
          name: c.name,
          frame: c.frame,
        })),
        changes: delta,
      });
      previous = state;
    }
    gzip.end();
    await finished(stream);
    resource.changedRecordCount = changes;
    resource.traceSha256 = hash(await readFile(join(options.output, filename)));
    entry.resources[kind] = resource;
    console.log(
      `${channel.shortId} ${kind}: ${options.frames + 1} numeric poses, ${changes} changed records`,
    );
  }
  inventory.channels.push(entry);
}
await writeFile(join(options.output, 'inventory.json'), formatJson(inventory));
await writeFile(
  join(options.output, 'README.txt'),
  `${inventory.notice}\n\nEach gzip JSONL begins with a header. Frame 0 contains the full numeric state; apply later frame changes by record name to reconstruct each pose.\nThe inventory lists every raw BRLAN track, default duration and interpreted scheduling controller, including unused source/data branches.\nFrame numbers are 60 Hz menu animation units, not an emulator frame capture. No NAND writes, channel execution or network requests occur.\n`,
);
console.log(`Inventory: ${join(options.output, 'inventory.json')}`);
